"""Exports the trained U-Net to ONNX for the app, and writes its metadata.

The model follows the contract in src/recognition/contract.ts: the input "image" [N, 1, H, W]
and the output "logits" [N, 4, H, W], with N, H, and W dynamic.

    uv run python export.py --checkpoint checkpoints/best.pt
"""

from __future__ import annotations

import argparse
import datetime
import json
import os

import numpy as np
import onnxruntime as ort
import torch

import generate
from model import CLASSES, UNet, parameters

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "public", "models", "recognition")
CONTRACT_VERSION = 1


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkpoint", default=os.path.join(HERE, "checkpoints", "best.pt"))
    parser.add_argument("--history", default=os.path.join(HERE, "checkpoints", "history.json"))
    args = parser.parse_args()

    model = UNet()
    model.load_state_dict(torch.load(args.checkpoint, map_location="cpu"))
    model.eval()
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, "floorplan.onnx")
    example = torch.rand(1, 1, 512, 512)
    torch.onnx.export(
        model,
        (example,),
        path,
        input_names=["image"],
        output_names=["logits"],
        dynamic_axes={"image": {0: "n", 2: "h", 3: "w"}, "logits": {0: "n", 2: "h", 3: "w"}},
        opset_version=17,
        dynamo=False,
    )

    # The ONNX output must equal the output of PyTorch, also for other sizes.
    session = ort.InferenceSession(path, providers=["CPUExecutionProvider"])
    rng = np.random.default_rng(99)
    worst = 0.0
    for h, w in ((512, 512), (768, 1024)):
        img, _ = generate.sample(rng, max(h, w))
        x = torch.from_numpy(img[:h, :w]).float()[None, None] / 255.0
        with torch.no_grad():
            expected = model(x).numpy()
        actual = session.run(["logits"], {"image": x.numpy()})[0]
        assert actual.shape == (1, 4, h, w), actual.shape
        worst = max(worst, float(np.abs(actual - expected).max()))
        print(f"{h}x{w}: max abs difference {np.abs(actual - expected).max():.2e}")

    history = {}
    if os.path.exists(args.history):
        with open(args.history) as f:
            history = json.load(f)
    last = history.get("history", [{}])[-1]
    info = {
        "contract": CONTRACT_VERSION,
        "classes": CLASSES,
        "long_side": generate.LONG_SIDE,
        "tile": generate.TILE,
        "parameters": parameters(model),
        "file_size": os.path.getsize(path),
        "training_minutes": history.get("minutes"),
        "training_steps": history.get("steps"),
        "validation_iou": dict(zip(CLASSES, [round(v, 4) for v in last.get("iou", [])])),
        "onnx_max_difference": worst,
        "date": datetime.date.today().isoformat(),
        "license": "Trained only on synthetic data generated by Grundriss. MPL-2.0.",
    }
    with open(os.path.join(OUT, "model.json"), "w") as f:
        json.dump(info, f, indent=2)
        f.write("\n")
    print(json.dumps(info, indent=2))


if __name__ == "__main__":
    main()
